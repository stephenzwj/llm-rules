#!/usr/bin/env python3
"""合并 custom.yaml 与上游 AI 规则集，生成 llm.yaml (Clash classical) 和 llm.list (Shadowrocket)。

用法: ./sync.py   （依赖 python3 + curl）
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).parent
BM7 = "https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/Clash"
META = "https://raw.githubusercontent.com/MetaCubeX/meta-rules-dat/meta/geo/geosite"
JXK = "https://raw.githubusercontent.com/jinxinkai/clash-ai-rules/refs/heads/master"

# (名称, URL, 纯域名条目是否视为 DOMAIN-SUFFIX)
UPSTREAM = [
    ("OpenAI (blackmatrix7)", f"{BM7}/OpenAI/OpenAI.yaml", False),
    ("Claude (blackmatrix7)", f"{BM7}/Claude/Claude.yaml", False),
    ("Gemini (blackmatrix7)", f"{BM7}/Gemini/Gemini.yaml", False),
    ("Copilot (blackmatrix7)", f"{BM7}/Copilot/Copilot.yaml", False),
    ("xAI / Grok (jinxinkai)", f"{JXK}/xAI.yaml", False),
    ("Muse / Meta AI (jinxinkai)", f"{JXK}/Muse.yaml", False),
    ("openai geosite (MetaCubeX)", f"{META}/openai.yaml", True),
    ("category-ai-!cn (MetaCubeX)", f"{META}/classical/category-ai-!cn.yaml", False),
]
NO_RESOLVE = ("IP-CIDR", "IP-CIDR6", "IP-ASN")


def fetch(url):
    # 用系统 curl，避免 python.org 版 Python 缺根证书的问题
    return subprocess.run(["curl", "-fsSL", "--max-time", "30", url],
                          check=True, capture_output=True, text=True).stdout


def parse(text, bare_is_suffix):
    rules = []
    for line in text.splitlines():
        m = re.match(r"^\s*-\s*(.+?)\s*$", line)
        if not m:
            continue
        r = m.group(1).strip("'\"")
        if "," not in r:
            if not bare_is_suffix:
                continue
            r = "DOMAIN-SUFFIX," + r.lstrip("+.")
        kind, *rest = r.split(",")
        if kind in NO_RESOLVE:
            rest = [x for x in rest if x != "no-resolve"] + ["no-resolve"]
        rules.append(",".join([kind, *rest]))
    return rules


def main():
    sections = [("custom.yaml", parse((ROOT / "custom.yaml").read_text(), False))]
    for name, url, bare in UPSTREAM:
        sections.append((name, parse(fetch(url), bare)))

    # 全局去重：完全相同的条目只保留第一次；被 DOMAIN-SUFFIX 覆盖的 DOMAIN 也丢弃
    suffixes = {r.split(",")[1] for _, rs in sections for r in rs if r.startswith("DOMAIN-SUFFIX,")}

    def covered(r):
        if not r.startswith("DOMAIN,"):
            return False
        parts = r.split(",")[1].split(".")
        return any(".".join(parts[i:]) in suffixes for i in range(len(parts)))

    seen, out = set(), []
    for name, rules in sections:
        kept = []
        for r in rules:
            if r in seen or covered(r):
                continue
            seen.add(r)
            kept.append(r)
        out.append((name, kept))

    head = "# Generated by sync.py from custom.yaml + upstream — do not edit; edit custom.yaml and rerun ./sync.py\n"
    yaml_lines, list_lines = [head + "payload:"], [head.rstrip()]
    for name, rules in out:
        if not rules:
            continue
        yaml_lines += ["", f"  # === {name} ({len(rules)}) ==="] + [f"  - {r}" for r in rules]
        list_lines += ["", f"# === {name} ({len(rules)}) ==="] + rules
    (ROOT / "llm.yaml").write_text("\n".join(yaml_lines) + "\n")
    (ROOT / "llm.list").write_text("\n".join(list_lines) + "\n")
    print({n: len(r) for n, r in out}, "total", sum(len(r) for _, r in out))


main()
